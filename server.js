require('dotenv').config?.();
const express=require('express');
const session=require('express-session');
const path=require('path');
const {initDatabase}=require('./src/database/sqlite');
const routes=require('./src/routes');
initDatabase();
const app=express();
const PORT=process.env.PORT||3000;
app.use(express.json());
app.use(express.urlencoded({extended:true}));
app.use(session({secret:process.env.SESSION_SECRET||'techcampus-dev-secret',resave:false,saveUninitialized:false,cookie:{httpOnly:true,sameSite:'lax',maxAge:8*60*60*1000}}));
app.use('/api',routes);
app.use(express.static(path.join(__dirname,'public')));
app.use((req,res)=>res.sendFile(path.join(__dirname,'public/index.html')));
app.listen(PORT,()=>console.log(`TechCampus rodando em http://localhost:${PORT}`));
